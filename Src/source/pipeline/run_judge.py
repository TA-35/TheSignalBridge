"""Batch eval harness: judge two rewrite sets over a source set (step 3).

Reads a source file (e.g. the gold set: id, source, signals) and two output
files (each record has at least id and rewrite, plus notes and meaning), runs
the position-swapped judge over every shared id, and writes per-pair verdicts
plus a summary: win counts, win rate, and the no_decision rate that flags
position bias.

Resumable: already-judged ids in judge_pairs.jsonl are skipped on a rerun.

Usage (from repo root):
  python -m Src.source.pipeline.run_judge \
      --source data/gold_drafts/enron_gold_draft.jsonl \
      --a eval/baseline.jsonl --a-name baseline \
      --b eval/run1.jsonl     --b-name run1 \
      --out eval/enron
"""
from __future__ import annotations
import argparse
import json
import sys
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path
from .judge import judge_pair

WORKERS = 5  # Run up to five judging tasks at the same time
def _read_jsonl(path):
    rows = []  # Store all records from the file

    with open(path, encoding="utf-8") as f:  # Open the JSONL file
        for line in f:  # Read the file one line at a time
            line = line.strip()  # Remove extra spaces and newline characters

            if line:
                rows.append(json.loads(line))  # Convert the JSON line into a Python dictionary

    return rows  # Return all the records

def _outputs_by_id(path):
    out = {}  # Store model outputs using their IDs

    for r in _read_jsonl(path):  # Go through each record in the output file
        rid, rw = r.get("id"), r.get("rewrite")  # Get the record ID and generated rewrite

        if rid and isinstance(rw, str) and rw.strip():  # Keep only records with a valid ID and non-empty rewrite
            out[rid] = {
                "meaning": r.get("meaning") or {},  # Get the meaning or use an empty dictionary
                "rewrite": rw.strip(),  # Remove extra spaces from the rewrite
                "notes": r.get("notes") or []  # Get the notes or use an empty list
            }

    return out  # Return all valid outputs organised by ID

def _done_ids(pairs_path):
    if not pairs_path.exists():
        return set()  # Return an empty set if no previous results exist

    return {
        r["id"] for r in _read_jsonl(pairs_path) if "id" in r
    }  # Get the IDs that have already been judged

def run(source_path, a_path, b_path, out_dir, a_name="a", b_name="b"):
    source = {
        r["id"]: r for r in _read_jsonl(source_path)
    }  # Load the source records and store them by ID

    out_a = _outputs_by_id(a_path)  # Load the rewrites generated by model A
    out_b = _outputs_by_id(b_path)  # Load the rewrites generated by model B

    shared = [
        i for i in source if i in out_a and i in out_b
    ]  # Keep only IDs that exist in the source and both model outputs

    out_dir = Path(out_dir)  # Convert the output folder path into a Path object
    out_dir.mkdir(parents=True, exist_ok=True)  # Create the output folder if needed

    pairs_path = out_dir / "judge_pairs.jsonl"  # File to store the result for each judged pair
    summary_path = out_dir / "judge_summary.json"  # File to store the final evaluation summary

    done = _done_ids(pairs_path)  # Find IDs that have already been evaluated

    todo = [
        i for i in shared if i not in done
    ]  # Keep only IDs that still need to be judged

    print(
        f"{len(shared)} shared ids, {len(done)} already judged, "
        f"{len(todo)} to go ({len(source) - len(shared)} ids missing an output)"
    )  # Show the total, completed, and remaining records

    def work(rid):
        rec = source[rid]  # Get the original source record for this ID

        return rid, judge_pair(
            rec["source"],
            rec.get("signals"),
            out_a[rid],
            out_b[rid]
        )  # Compare both rewrites using the original message and its signals

    label = {"a": a_name, "b": b_name}  # Map A and B to their actual model names
    errors = 0  # Count errors that happen during this run

    with open(pairs_path, "a", encoding="utf-8") as f, \
         ThreadPoolExecutor(max_workers=WORKERS) as pool:  # Open the results file and create a pool of five workers

        futures = {
            pool.submit(work, rid): rid for rid in todo
        }  # Submit all remaining records for parallel judging

        for i, fut in enumerate(as_completed(futures), 1):  # Process each judging task as soon as it finishes
            rid = futures[fut]  # Get the ID of the completed task

            try:
                rid, res = fut.result()  # Get the ID and judge result from the completed task

            except Exception as exc:
                errors += 1  # Increase the error count if judging fails

                print(
                    f"  {rid}: ERROR {type(exc).__name__}: {exc}",
                    file=sys.stderr
                )  # Display the failed ID and error details

                continue  # Skip the failed record and continue with the others

            f.write(json.dumps({
                "id": rid,  # Save the ID of the judged record
                "winner": label.get(res.winner, res.winner),  # Save the winning model name or other verdict
                "agree": res.agree,  # Save whether both judging orders agreed
                "order_ab": {
                    "winner": res.order_ab.winner,  # Save the winner when A is shown before B
                    "reason": res.order_ab.reason  # Save the reason for the A/B result
                },
                "order_ba": {
                    "winner": res.order_ba.winner,  # Save the winner when B is shown before A
                    "reason": res.order_ba.reason  # Save the reason for the B/A result
                },
            }, ensure_ascii=False) + "\n")  # Write the complete judgment as one JSON line

            f.flush()  # Save the result immediately so progress is not lost

            if i % 10 == 0:
                print(f"  {i}/{len(todo)} done")  # Show progress after every ten completed tasks

    rows = _read_jsonl(pairs_path)  # Load all saved judgments including previous runs

    wins_a = sum(1 for r in rows if r["winner"] == a_name)  # Count how many times model A won
    wins_b = sum(1 for r in rows if r["winner"] == b_name)  # Count how many times model B won
    ties = sum(1 for r in rows if r["winner"] == "tie")  # Count cases where neither model was preferred
    nodec = sum(1 for r in rows if r["winner"] == "no_decision")  # Count cases where the judge could not make a consistent decision

    n = len(rows)  # Get the total number of saved judgments
    decided = wins_a + wins_b  # Count judgments where either A or B won

    summary = {
        "source": str(source_path),  # Store the source file used for evaluation
        "a_name": a_name,  # Store model A's name
        "b_name": b_name,  # Store model B's name
        "pairs_judged": n,  # Store the total number of judged pairs
        "errors_this_run": errors,  # Store the number of errors in the current run
        f"wins_{a_name}": wins_a,  # Store model A's win count
        f"wins_{b_name}": wins_b,  # Store model B's win count
        "ties": ties,  # Store the number of tied results
        "no_decision": nodec,  # Store the number of undecided results
        f"win_rate_{b_name}_vs_{a_name}": round(wins_b / decided, 3) if decided else None,  # Calculate B's win rate using only A/B wins
        "position_bias_rate": round(nodec / n, 3) if n else None,  # Calculate the percentage of results with no decision
    }

    summary_path.write_text(
        json.dumps(summary, indent=2),
        encoding="utf-8"
    )  # Save the final summary as a readable JSON file

    print(json.dumps(summary, indent=2))  # Display the evaluation summary

def main():
    p = argparse.ArgumentParser(description="Batch position-swapped LLM judge")  # Create the command-line argument parser
    p.add_argument("--source", required=True, help="source/gold jsonl (id, source, signals)")  # Get the original source file
    p.add_argument("--a", required=True, help="output set A jsonl (id, rewrite, notes, meaning)")  # Get model A's output file
    p.add_argument("--b", required=True, help="output set B jsonl (id, rewrite, notes, meaning)")  # Get model B's output file
    p.add_argument("--a-name", default="a")  # Set the name for model A
    p.add_argument("--b-name", default="b")  # Set the name for model B
    p.add_argument("--out", required=True, help="output directory")  # Get the folder where results will be saved
    args = p.parse_args()  # Read the arguments provided in the command
    run(args.source, args.a, args.b, args.out, args.a_name, args.b_name)  # Start the evaluation using the given files and model names

if __name__ == "__main__":
    main()  # Run the evaluation when this script is executed directly